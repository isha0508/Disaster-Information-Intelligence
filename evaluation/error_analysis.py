"""
evaluation/error_analysis.py
==============================
Systematic error analysis for the humanitarian category classifier.

Requires:
    evaluation/results/humanitarian/test_predictions.csv
    (generated by training/train_humanitarian.py)

Run:
    python evaluation/error_analysis.py
"""

import sys
from pathlib import Path
from collections import Counter

import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from preprocessing.humaid_loader import HUMAID_CLASSES

PREDS_CSV   = ROOT / "evaluation" / "results" / "humanitarian" / "test_predictions.csv"
FIGURES_DIR = ROOT / "evaluation" / "figures" / "humanitarian"
OUT_MD      = ROOT / "docs" / "classification_error_analysis.md"
FIGURES_DIR.mkdir(parents=True, exist_ok=True)

if not PREDS_CSV.exists():
    print(f"ERROR: {PREDS_CSV} not found.")
    print("Run training/train_humanitarian.py first.")
    sys.exit(1)

df = pd.read_csv(PREDS_CSV)
errors  = df[df["correct"] == False].copy()
correct = df[df["correct"] == True].copy()

print(f"Total test examples : {len(df):,}")
print(f"Correct             : {len(correct):,}  ({100*len(correct)/len(df):.1f}%)")
print(f"Errors              : {len(errors):,}  ({100*len(errors)/len(df):.1f}%)")

# ── 1. Error rate per class ───────────────────────────────────────────────────
print("\n── Error rate per class ──")
class_error_rates = {}
for lbl in HUMAID_CLASSES:
    subset = df[df["class_label"] == lbl]
    if len(subset) == 0:
        continue
    err_rate = 1 - subset["correct"].mean()
    class_error_rates[lbl] = err_rate
    print(f"  {lbl:<50} error={err_rate:.3f}  "
          f"({int(err_rate*len(subset))}/{len(subset)})")

# ── 2. Most common confusion pairs ───────────────────────────────────────────
print("\n── Top 20 confusion pairs (actual → predicted) ──")
confusion_pairs = Counter(zip(errors["class_label"], errors["predicted"]))
top_pairs = confusion_pairs.most_common(20)
for (actual, pred), count in top_pairs:
    print(f"  {actual:<50} → {pred:<50}  count={count}")

# ── 3. Specific confusion clusters of interest ───────────────────────────────
CONFUSIONS_OF_INTEREST = [
    ("requests_or_urgent_needs",          "rescue_volunteering_or_donation_effort"),
    ("rescue_volunteering_or_donation_effort", "requests_or_urgent_needs"),
    ("injured_or_dead_people",            "other_relevant_information"),
    ("other_relevant_information",        "injured_or_dead_people"),
    ("infrastructure_and_utility_damage", "other_relevant_information"),
    ("other_relevant_information",        "infrastructure_and_utility_damage"),
    ("caution_and_advice",                "sympathy_and_support"),
    ("sympathy_and_support",              "caution_and_advice"),
]

print("\n── Confusion clusters of interest ──")
cluster_examples = {}
for actual, pred in CONFUSIONS_OF_INTEREST:
    subset = errors[(errors["class_label"] == actual) & (errors["predicted"] == pred)]
    cluster_examples[(actual, pred)] = subset
    print(f"\n  {actual} → {pred}  ({len(subset)} cases)")
    for _, row in subset.head(3).iterrows():
        print(f"    conf={row['confidence']:.2f}  |  {row['tweet_text'][:120]}")

# ── 4. Minority class failures ────────────────────────────────────────────────
print("\n── missing_or_found_people errors ──")
mfp_errors = errors[errors["class_label"] == "missing_or_found_people"]
print(f"  Errors: {len(mfp_errors)} / {len(df[df['class_label']=='missing_or_found_people'])}")
for _, row in mfp_errors.head(5).iterrows():
    print(f"  → predicted: {row['predicted']:<40} | {row['tweet_text'][:100]}")

# ── 5. Short tweet analysis ───────────────────────────────────────────────────
df["word_count"] = df["tweet_text"].apply(lambda t: len(str(t).split()))
errors  = df[df["correct"] == False].copy()   # refresh with word_count column
correct = df[df["correct"] == True].copy()
short_errors = errors[errors["word_count"] <= 8]
short_correct= correct[correct["word_count"] <= 8]
short_error_rate = len(short_errors) / max(len(short_errors) + len(short_correct), 1)
print(f"\n── Short tweets (≤8 words) ──")
print(f"  Error rate: {short_error_rate:.3f}  "
      f"({len(short_errors)} errors / {len(short_errors)+len(short_correct)} short tweets)")
print(f"  Overall error rate: {len(errors)/len(df):.3f}")

# ── 6. Low-confidence correct and high-confidence wrong ──────────────────────
high_conf_wrong = errors[errors["confidence"] > 0.8]
low_conf_correct= correct[correct["confidence"] < 0.5]
print(f"\n── High-confidence wrong predictions (conf>0.8): {len(high_conf_wrong)} ──")
for _, row in high_conf_wrong.head(5).iterrows():
    print(f"  actual={row['class_label']:<40} pred={row['predicted']:<40} "
          f"conf={row['confidence']:.2f}")
    print(f"    {row['tweet_text'][:120]}")

# ── 7. Error heatmap (normalized) ─────────────────────────────────────────────
from sklearn.metrics import confusion_matrix
cm = confusion_matrix(df["class_label"], df["predicted"], labels=HUMAID_CLASSES)
cm_norm = cm.astype(float) / (cm.sum(axis=1, keepdims=True) + 1e-9)
short_labels = [l.replace("_", "\n") for l in HUMAID_CLASSES]
fig, ax = plt.subplots(figsize=(14, 11))
sns.heatmap(cm_norm, annot=True, fmt=".2f", cmap="Reds",
            xticklabels=short_labels, yticklabels=short_labels,
            ax=ax, annot_kws={"size": 8}, vmin=0, vmax=1)
ax.set_xlabel("Predicted"); ax.set_ylabel("Actual")
ax.set_title("Humanitarian Classifier — Normalized Confusion Matrix (row %)")
plt.xticks(fontsize=7, rotation=45, ha="right")
plt.yticks(fontsize=7, rotation=0)
plt.tight_layout()
plt.savefig(FIGURES_DIR / "normalized_confusion_matrix.png", dpi=150, bbox_inches="tight")
plt.close()

# ── 8. Error rate per class bar chart ─────────────────────────────────────────
sorted_items = sorted(class_error_rates.items(), key=lambda x: -x[1])
labels_sorted = [l.replace("_", "\n") for l, _ in sorted_items]
rates_sorted  = [r for _, r in sorted_items]
colors = ["#d62728" if r > 0.4 else "#ff7f0e" if r > 0.2 else "#2ca02c"
          for r in rates_sorted]
fig, ax = plt.subplots(figsize=(13, 5))
ax.bar(range(len(labels_sorted)), rates_sorted, color=colors)
ax.set_xticks(range(len(labels_sorted)))
ax.set_xticklabels(labels_sorted, fontsize=7, rotation=45, ha="right")
ax.set_ylabel("Error Rate")
ax.set_ylim(0, 1.0)
ax.set_title("Humanitarian Classifier — Error Rate per Class (Test)")
for i, r in enumerate(rates_sorted):
    ax.text(i, r + 0.02, f"{r:.2f}", ha="center", fontsize=8)
plt.tight_layout()
plt.savefig(FIGURES_DIR / "error_rate_per_class.png", dpi=150, bbox_inches="tight")
plt.close()

# ── 9. Representative misclassified examples (20+) ───────────────────────────
print("\n── 20 representative misclassified examples ──")
sample_errors = errors.sample(min(20, len(errors)), random_state=42)
for i, (_, row) in enumerate(sample_errors.iterrows(), 1):
    print(f"\n  [{i:02d}] actual={row['class_label']}")
    print(f"       pred  ={row['predicted']}  conf={row['confidence']:.2f}")
    print(f"       text  : {row['tweet_text'][:140]}")

# ── 10. Write markdown report ─────────────────────────────────────────────────
total = len(df)
n_err = len(errors)
overall_acc = correct["correct"].mean() if len(correct) else 0

lines = [
    "# Classification Error Analysis — Humanitarian Category Classifier",
    "",
    "**Model:** TF-IDF + Logistic Regression (balanced class weights)  ",
    "**Dataset:** HumAID test split  ",
    "**Generated by:** `evaluation/error_analysis.py`",
    "",
    "---",
    "",
    "## 1. Overall Error Summary",
    "",
    f"| Metric | Value |",
    f"|---|---|",
    f"| Total test examples | {total:,} |",
    f"| Correctly classified | {len(correct):,} ({100*len(correct)/total:.1f}%) |",
    f"| Misclassified | {n_err:,} ({100*n_err/total:.1f}%) |",
    f"| Short tweet (≤8 words) error rate | {short_error_rate:.3f} vs {n_err/total:.3f} overall |",
    f"| High-confidence wrong (conf>0.8) | {len(high_conf_wrong):,} |",
    "",
    "---",
    "",
    "## 2. Error Rate per Class",
    "",
    "| Class | Error Rate | Errors / Total |",
    "|---|---:|---:|",
]
for lbl, rate in sorted_items:
    subset = df[df["class_label"] == lbl]
    n_class_err = int(rate * len(subset))
    lines.append(f"| {lbl} | {rate:.3f} | {n_class_err}/{len(subset)} |")

lines += [
    "",
    "---",
    "",
    "## 3. Top Confusion Pairs",
    "",
    "| Actual → Predicted | Count |",
    "|---|---:|",
]
for (actual, pred), count in top_pairs:
    lines.append(f"| {actual} → {pred} | {count} |")

lines += [
    "",
    "---",
    "",
    "## 4. Confusion Clusters of Interest",
    "",
    "### Why these pairs are confused",
    "",
    "**requests_or_urgent_needs ↔ rescue_volunteering_or_donation_effort**  ",
    "Both classes describe resource mobilization. The distinction is directionality: ",
    "'requests' is needs-seeking, 'rescue/donation' is supply-offering. Short tweets ",
    "that mention 'food', 'water', or 'help' without clear directionality fall in between.",
    "",
    "**injured_or_dead_people ↔ other_relevant_information**  ",
    "Some casualty tweets phrase the event factually ('earthquake report: 17 confirmed dead') ",
    "which resembles general information reporting. The model struggles when casualty framing ",
    "is indirect.",
    "",
    "**infrastructure_and_utility_damage ↔ other_relevant_information**  ",
    "Infrastructure tweets often embed damage descriptions within broader event summaries. ",
    "The boundary between 'damage report' and 'general update' is ambiguous.",
    "",
    "**caution_and_advice ↔ sympathy_and_support**  ",
    "Both are often empathetic in tone. Advice tweets that express sympathy alongside ",
    "practical guidance can trigger sympathy predictions.",
    "",
    "---",
    "",
    "## 5. Minority Class Failure (missing_or_found_people)",
    "",
    f"The `missing_or_found_people` class has the fewest training examples (250 in train).  ",
    f"Errors on this class are expected due to:",
    "- Severe underrepresentation (~0.5% of data)",
    "- Language overlap with `injured_or_dead_people` and `other_relevant_information`",
    "- Class-weighted LR partially compensates but cannot fully bridge 250 vs 14,891 examples",
    "",
    "---",
    "",
    "## 6. Short Tweet Failures",
    "",
    f"Short tweets (≤8 words) have error rate **{short_error_rate:.3f}** vs **{n_err/total:.3f}** overall.",
    "Likely causes:",
    "- Insufficient vocabulary for disambiguation",
    "- Hashtag-only tweets where the topic word is the entire signal",
    "- Out-of-context fragments (e.g., retweet fragments without context)",
    "",
    "---",
    "",
    "## 7. High-Confidence Wrong Predictions",
    "",
    f"**{len(high_conf_wrong)}** predictions had confidence >0.8 but were wrong.  ",
    "These are the most concerning failures — the model is confidently incorrect.  ",
    "Likely causes: vocabulary overlap between classes, ambiguous framing, and the model ",
    "learning surface-level cues (keywords) rather than deeper semantics.",
    "",
    "---",
    "",
    "## 8. Representative Misclassified Examples (20 samples)",
    "",
]
for i, (_, row) in enumerate(sample_errors.iterrows(), 1):
    lines += [
        f"**[{i:02d}]**  ",
        f"- Actual: `{row['class_label']}`  ",
        f"- Predicted: `{row['predicted']}` (confidence: {row['confidence']:.2f})  ",
        f"- Tweet: *{row['tweet_text'][:200]}*",
        "",
    ]

lines += [
    "---",
    "",
    "## 9. Summary of Error Causes",
    "",
    "| Error Type | Evidence | Impact |",
    "|---|---|---|",
    "| Class imbalance | missing_or_found_people has 250 train examples | High — minority class recall very low |",
    "| Vocabulary overlap | requests ↔ rescue confusion | Medium — both use resource/help vocabulary |",
    "| Short tweets | Higher error rate on ≤8 word tweets | Low-medium — relatively few short tweets |",
    "| Ambiguous framing | high-confidence wrong predictions | Medium — model overconfident on surface keywords |",
    "| Indirect casualty reporting | injured↔other confusion | Low — most casualty tweets are direct |",
    "",
    "---",
    "",
    "## 10. Recommended Improvements",
    "",
    "1. **For missing_or_found_people**: Oversample or apply targeted data augmentation; ",
    "   the class-weight penalty alone is insufficient at 56:1 imbalance.",
    "2. **For requests↔rescue confusion**: Feature engineering — add syntactic role signals ",
    "   (passive vs active voice, directional verbs).",
    "3. **For short tweets**: Ensemble with a character n-gram model which handles ",
    "   short, hashtag-heavy text better than word n-grams.",
    "4. **Overall**: The Transformer model should improve disambiguation through contextual ",
    "   representations; compare transformer per-class F1 against TF-IDF baseline.",
    "",
    "---",
    "",
    "*Generated by: evaluation/error_analysis.py — internal project artifact*",
]

OUT_MD.write_text("\n".join(lines), encoding="utf-8")
print(f"\nError analysis report saved: {OUT_MD}")
print("\nError analysis complete.")
